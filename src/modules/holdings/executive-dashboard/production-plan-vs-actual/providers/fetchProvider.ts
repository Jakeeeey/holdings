export async function fetchProductionPlanVsActual({
  groupId,
  startDate,
  endDate,
  branchId,
  force = false,
}: FetchProductionPlanParams): Promise<ProductionPlanVsActualResponse> {
  const params = new URLSearchParams();
  if (startDate) params.set("startDate", startDate);
  if (endDate) params.set("endDate", endDate);
  if (branchId && branchId !== "all") params.set("branchId", String(branchId));
  if (force) params.set("force", "true");

  const url = `/api/holdings/executive-dashboard/manufacturing/${groupId}/plan-vs-actual?${params.toString()}`;

  try {
    const res = await fetch(url, {
      method: "GET",
      cache: force ? "no-store" : "default",
      headers: { "Content-Type": "application/json" },
    });

    if (!res.ok) {
      console.warn(`[fetchProductionPlanVsActual] Server responded with status ${res.status}`);
      return FALLBACK_PRODUCTION_PLAN_DATA;
    }

    const data: ProductionPlanVsActualResponse = await res.json();
    return data;
  } catch (err) {
    console.warn("[fetchProductionPlanVsActual] Error fetching data, using fallback:", err);
    return FALLBACK_PRODUCTION_PLAN_DATA;
  }
}

