const clientCache = new Map<string, { data: ProductionWastageResponse; timestamp: number }>();
const CLIENT_CACHE_TTL_MS = 20000;

export async function fetchProductionWastage(
  params: FetchWastageParams
): Promise<ProductionWastageResponse> {
  const { groupId, startDate, endDate, category, force } = params;

  const q = new URLSearchParams();
  if (startDate) q.set("startDate", startDate);
  if (endDate) q.set("endDate", endDate);
  if (category) q.set("category", category);
  if (force) q.set("force", "true");

  const url = `/api/holdings/executive-dashboard/manufacturing/${groupId}/wastage?${q.toString()}`;
  const cacheKey = `${groupId}_${startDate || ""}_${endDate || ""}_${category || ""}`;

  if (!force && clientCache.has(cacheKey)) {
    const entry = clientCache.get(cacheKey)!;
    if (Date.now() - entry.timestamp < CLIENT_CACHE_TTL_MS) {
      return entry.data;
    }
  }

  try {
    const res = await fetch(url, {
      method: "GET",
      headers: { "Content-Type": "application/json" },
      cache: "no-store",
    });

    if (!res.ok) {
      console.warn(`[fetchProductionWastage] API returned status ${res.status}`);
      return FALLBACK_PRODUCTION_WASTAGE_DATA;
    }

    const data: ProductionWastageResponse = await res.json();
    clientCache.set(cacheKey, { data, timestamp: Date.now() });
    return data;
  } catch (error) {
    console.error("[fetchProductionWastage] Network error, using fallback:", error);
    return FALLBACK_PRODUCTION_WASTAGE_DATA;
  }
}

