export async function fetchRawMaterialAvailability({
  groupId,
  startDate,
  endDate,
  category,
  force = false,
}: FetchRawMaterialParams): Promise<RawMaterialAvailabilityResponse> {
  const params = new URLSearchParams();
  if (startDate) params.set("startDate", startDate);
  if (endDate) params.set("endDate", endDate);
  if (category && category !== "all") params.set("category", category);
  if (force) params.set("force", "true");

  const url = `/api/holdings/executive-dashboard/manufacturing/${groupId}/materials?${params.toString()}`;

  try {
    const res = await fetch(url, {
      method: "GET",
      cache: force ? "no-store" : "default",
      headers: { "Content-Type": "application/json" },
    });

    if (!res.ok) {
      console.warn(`[fetchRawMaterialAvailability] Server responded with status ${res.status}`);
      return FALLBACK_RAW_MATERIAL_DATA;
    }

    const data: RawMaterialAvailabilityResponse = await res.json();
    return data;
  } catch (err) {
    console.warn("[fetchRawMaterialAvailability] Error fetching data, using fallback:", err);
    return FALLBACK_RAW_MATERIAL_DATA;
  }
}

