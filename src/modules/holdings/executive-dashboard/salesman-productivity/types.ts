export type ProductivityTier = "ELITE" | "ON_TRACK" | "MODERATE" | "UNDERPERFORMING";

export interface SalesmanProductivityItem {
  salesmanId: number;
  name: string;
  code: string;
  branchId: number;
  branchName: string;
  truckPlate?: string;
  totalRevenue: number;
  invoiceCount: number;
  uniqueCustomersCount: number;
  averageDropSize: number;
  targetAmount: number;
  quotaAchievementRate: number;
  tier: ProductivityTier;
  latestInvoiceDate?: string | null;
}

export interface DepotProductivitySummary {
  branchId: number;
  branchName: string;
  salesmanCount: number;
  invoiceCount: number;
  totalRevenue: number;
  averageDropSize: number;
  averageQuotaAttainment: number;
}

export interface TrendProductivityPoint {
  date: string;
  periodLabel: string;
  revenue: number;
  invoicesCount: number;
  activeSalesmenCount: number;
  averageDropSize: number;
}

export interface SalesmanProductivityKpis {
  totalRevenue: number; // ₱ Total Sales generated by sales force
  totalInvoicesCount: number; // Productive calls/transactions
  activeSalesmenCount: number; // Number of active field representatives
  totalOutletsReached: number; // Unique retail/wholesale accounts served
  averageDropSize: number; // ₱ Average order value per invoice
  averageQuotaAttainment: number; // % Weighted average quota completion
  topPerformerName: string;
  topPerformerRevenue: number;
  eliteRepsCount: number;
  underperformingRepsCount: number;
}

export interface SalesmanProductivityFilters {
  startDate?: string | null;
  endDate?: string | null;
  branchId?: number | null;
  tier?: string | null;
  search?: string | null;
}

export interface SalesmanProductivityResponse {
  kpis: SalesmanProductivityKpis;
  salesmen: SalesmanProductivityItem[];
  depots: DepotProductivitySummary[];
  trends: TrendProductivityPoint[];
  filters: SalesmanProductivityFilters;
  source: "live_engine" | "fallback_mock";
  timestamp: string;
}

